"""Generate a standalone pyusb driver from an inferred protocol."""
from __future__ import annotations
import inspect
import re

from . import checksums
from .infer import Protocol

HEADER = '''"""Open-source driver for USB device {ids}.

Generated by usb-rea (https://github.com/emirmrkaljevic/usb-rea) from captured traffic.
Every encoding below is backed by frames listed in the accompanying report.md.
Review before use: sending commands to hardware is at your own risk.
"""
import usb.core

VID = {vid}
PID = {pid}

# ---- checksums (copied from usb_rea.checksums) ----
{checksums}
# ---- generic encoder ----
def _put(b, off, width, endian, v):
    v &= (1 << (8 * width)) - 1
    b[off:off + width] = v.to_bytes(width, "little" if endian == "le" else "big")


def encode(spec, values, seq=0):
    b = bytearray.fromhex(spec["template"])
    for f in spec["fields"]:
        kind, off, w, end = f["kind"], f["offset"], f["width"], f["endian"]
        if kind == "value":
            _put(b, off, w, end, int(round(values[f["index"]] * f["scale"] + f["bias"] + 1e-9)))
        elif kind == "bitfield":
            bo, bw = f["bit_offset"], f["bit_width"]
            v = int(round(values[f["index"]] * f["scale"] + f["bias"] + 1e-9)) & ((1 << bw) - 1)
            span = int.from_bytes(b[off:off + w], "little")
            mask = ((1 << bw) - 1) << bo
            span = (span & ~mask) | (v << bo)
            b[off:off + w] = span.to_bytes(w, "little")
        elif kind == "lookup":
            v = float(values[f["index"]])
            if v not in f["table"]:
                raise ValueError(f"value {{v:g}} was never captured; known: {{sorted(f['table'])}}")
            _put(b, off, w, end, f["table"][v])
        elif kind == "counter":
            _put(b, off, w, end, seq * f["step"])
    for f in spec["fields"]:
        if f["kind"] == "checksum":
            a, z = f["covers"]
            _put(b, f["offset"], f["width"], f["endian"], compute(f["algo"], b[a:z]))
    return bytes(b)


class Device:
    def __init__(self, dev=None):
        self.dev = dev or usb.core.find(idVendor=VID, idProduct=PID)
        if self.dev is None:
            raise RuntimeError(f"device {{VID:04x}}:{{PID:04x}} not found")
        self.seq = 0
        for cfg in self.dev:
            for intf in cfg:
                if self.dev.is_kernel_driver_active(intf.bInterfaceNumber):
                    try:
                        self.dev.detach_kernel_driver(intf.bInterfaceNumber)
                    except usb.core.USBError:
                        pass

    def _send(self, spec, *values):
        self.seq += 1
        data = encode(spec, values, self.seq)
        if spec["setup"]:
            bm, req, wv, wi = spec["setup"]
            return self.dev.ctrl_transfer(bm, req, wv, wi, data)
        return self.dev.write(spec["endpoint"], data)
'''


def _ident(name: str) -> str:
    s = re.sub(r"\W+", "_", name).strip("_").lower() or "cmd"
    return s if not s[0].isdigit() else "cmd_" + s


def generate(proto: Protocol) -> str:
    vid = f"0x{proto.vid:04x}" if proto.vid is not None else "None  # TODO: set from lsusb"
    pid = f"0x{proto.pid:04x}" if proto.pid is not None else "None  # TODO: set from lsusb"
    ids = f"{proto.vid:04x}:{proto.pid:04x}" if proto.vid is not None else "(unknown id)"
    out = [HEADER.format(vid=vid, pid=pid, ids=ids, checksums=inspect.getsource(checksums).split('"""', 2)[2])]
    specs = []
    for c in proto.commands:
        setup = None
        if c.setup:
            s = c.setup
            setup = (s[0], s[1], s[2] | s[3] << 8, s[4] | s[5] << 8)
        fields = [dict(kind=f.kind, offset=f.offset, width=f.width, endian=f.endian, index=f.index,
                       scale=f.scale, bias=f.bias, table=f.table, step=f.step, algo=f.algo, covers=f.covers,
                       bit_offset=f.bit_offset, bit_width=f.bit_width)
                  for f in c.fields if f.kind in ("value", "bitfield", "lookup", "counter", "checksum")]
        const = _ident(c.name).upper()
        specs.append(f"{const} = {dict(template=c.template().hex(), endpoint=c.endpoint, setup=setup, fields=fields)!r}\n")
        args = ", ".join(f"v{i}" for i in range(c.arity))
        sig = f"self, {args}" if args else "self"
        frames = ", ".join(map(str, c.frames[:8]))
        lines = "; ".join(f"byte {f.offset}: {f.describe()}" for f in c.fields if f.kind not in ("const",))
        out.append(f'''
    def set_{_ident(c.name)}({sig}):
        """{c.name} ({c.confidence:.0%} confidence; evidence frames {frames}).

        {lines}
        """
        return self._send({const}{", " + args if args else ""})
''')
    head, cls = out[0].split("class Device:", 1)
    out[0] = head + "# ---- message specs (from inference) ----\n" + "".join(specs) + "\n\nclass Device:" + cls
    out.append('''

if __name__ == "__main__":
    import sys
    d = Device()
    name, *args = sys.argv[1:]
    print(getattr(d, "set_" + name)(*map(float, args)))
''')
    return "".join(out)
