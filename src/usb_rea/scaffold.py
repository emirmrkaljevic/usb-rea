"""Generate a standalone pyusb driver from an inferred protocol."""
from __future__ import annotations
import re
from .infer import Protocol

HEADER = '''"""Open-source driver for USB device {ids}.

Generated by usb-rea (https://github.com/emirmrkaljevic/usb-rea) from captured traffic.
Every encoding below is backed by frames listed in the accompanying report.md.
Review before use: replaying commands to hardware is at your own risk.
"""
import usb.core
import usb.util

VID = {vid}
PID = {pid}

CHECKSUMS = {{
    "sum8": lambda b: sum(b) & 0xFF,
    "xor8": lambda b: __import__("functools").reduce(lambda a, c: a ^ c, b, 0),
    "neg_sum8": lambda b: (-sum(b)) & 0xFF,
    "inv_sum8": lambda b: (~sum(b)) & 0xFF,
}}


class Device:
    def __init__(self, dev=None):
        self.dev = dev or usb.core.find(idVendor=VID, idProduct=PID)
        if self.dev is None:
            raise RuntimeError(f"device {{VID:04x}}:{{PID:04x}} not found")
        for cfg in self.dev:
            for intf in cfg:
                if self.dev.is_kernel_driver_active(intf.bInterfaceNumber):
                    try:
                        self.dev.detach_kernel_driver(intf.bInterfaceNumber)
                    except usb.core.USBError:
                        pass

    def _send(self, xfer, ep, setup, data):
        if xfer == "control":
            bm, req, wv, wi = setup
            return self.dev.ctrl_transfer(bm, req, wv, wi, data)
        return self.dev.write(ep, data)

    @staticmethod
    def _encode(template, values, checksums):
        b = bytearray(template)
        for off, (scale, bias, v) in values.items():
            b[off] = int(round(v * scale + bias + 1e-9)) & 0xFF
        for off, (algo, a, z) in checksums.items():
            b[off] = CHECKSUMS[algo](b[a:z])
        return bytes(b)
'''


def _ident(name: str) -> str:
    s = re.sub(r"\W+", "_", name).strip("_").lower() or "cmd"
    return s if not s[0].isdigit() else "cmd_" + s


def generate(proto: Protocol) -> str:
    vid = f"0x{proto.vid:04x}" if proto.vid is not None else "None  # TODO: set from lsusb"
    pid = f"0x{proto.pid:04x}" if proto.pid is not None else "None  # TODO: set from lsusb"
    ids = f"{proto.vid:04x}:{proto.pid:04x}" if proto.vid is not None else "(unknown id)"
    out = [HEADER.format(vid=vid, pid=pid, ids=ids)]
    for c in proto.commands:
        has_val = any(f.kind == "value" for f in c.fields)
        sig = "self, value" if has_val else "self"
        setup = None
        if c.setup:
            s = c.setup
            setup = (s[0], s[1], s[2] | s[3] << 8, s[4] | s[5] << 8)
        vals = {f.offset: (f.scale, f.bias) for f in c.fields if f.kind == "value"}
        css = {f.offset: (f.algo, *f.covers) for f in c.fields if f.kind == "checksum"}
        frames = ", ".join(map(str, c.frames[:8]))
        out.append(f'''
    def set_{_ident(c.name)}({sig}):
        """{c.name}: confidence {c.confidence:.0%}; evidence frames {frames}."""
        data = self._encode(
            bytes.fromhex("{c.template().hex()}"),
            {{{", ".join(f"{o}: ({s!r}, {b!r}, value)" for o, (s, b) in vals.items())}}},
            {{{", ".join(f"{o}: ({a!r}, {x}, {y})" for o, (a, x, y) in css.items())}}},
        )
        return self._send("{"control" if c.xfer_type == 2 else "ep"}", 0x{c.endpoint:02x}, {setup!r}, data)
''')
    out.append('''

if __name__ == "__main__":
    import sys
    d = Device()
    name, *arg = sys.argv[1:]
    fn = getattr(d, "set_" + name)
    print(fn(float(arg[0])) if arg else fn())
''')
    return "".join(out)
