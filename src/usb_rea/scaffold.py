HEADER = '''"""Open-source driver for USB device {ids}.

Generated by usb-rea (https://github.com/emirmrkaljevic/usb-rea) from captured traffic.
Every encoding below is backed by frames listed in the accompanying report.md.
Review before use: sending commands to hardware is at your own risk.
"""
import usb.core

VID = {vid}
PID = {pid}

# ---- checksums (copied from usb_rea.checksums) ----
{checksums}
# ---- generic encoder ----
def _put(b, off, width, endian, v):
    v &= (1 << (8 * width)) - 1
    b[off:off + width] = v.to_bytes(width, "little" if endian == "le" else "big")


def encode(spec, values, seq=0, prev=(), session=()):
    b = bytearray.fromhex(spec["template"])
    for f in spec["fields"]:
        kind, off, w, end = f["kind"], f["offset"], f["width"], f["endian"]
        if kind == "value":
            _put(b, off, w, end, int(round(values[f["index"]] * f["scale"] + f["bias"] + 1e-9)))
        elif kind == "bitfield":
            bo, bw = f["bit_offset"], f["bit_width"]
            v = int(round(values[f["index"]] * f["scale"] + f["bias"] + 1e-9)) & ((1 << bw) - 1)
            span = int.from_bytes(b[off:off + w], "little")
            mask = ((1 << bw) - 1) << bo
            span = (span & ~mask) | (v << bo)
            b[off:off + w] = span.to_bytes(w, "little")
        elif kind == "lookup":
            v = float(values[f["index"]])
            if v not in f["table"]:
                raise ValueError(f"value {{v:g}} was never captured; known: {{sorted(f['table'])}}")
            _put(b, off, w, end, f["table"][v])
        elif kind == "counter":
            _put(b, off, w, end, seq * f["step"])
        elif kind == "session" and len(session) > f["step"] and session[f["step"]]:
            # bytes copied from a handshake reply of this session (else the captured ones stay)
            b[off:off + w] = session[f["step"]][f["at"]:f["at"] + w]
    for f in spec["fields"]:
        if f["kind"] == "checksum":
            a, z = f["covers"]
            src = b if f.get("source") is None else prev[f["source"]]
            _put(b, f["offset"], f["width"], f["endian"], compute(f["algo"], src[a:z]))
    return bytes(b)


def _check_reply(step, spec, data):
    """Compare a handshake reply with the captured one: fixed bytes must match, a checksum must hold."""
    want = spec["expect"].split()
    bad = len(data) < len(want) or any(w != "??" and int(w, 16) != data[k] for k, w in enumerate(want))
    ck = spec.get("checksum")
    if not bad and ck:
        n, w = len(want), ck["width"]
        got = int.from_bytes(data[n - w:n], "little" if ck["endian"] == "le" else "big")
        bad = got != compute(ck["algo"], data[ck["covers"][0]:ck["covers"][1]])
    if bad:
        raise RuntimeError(f"handshake step {{step}}: reply {{bytes(data).hex(' ')}}, expected {{spec['expect']}}"
                           " (Device(handshake=False) or open(check=False) skips the check)")


class Device:
    def __init__(self, dev=None, handshake=True):
        self.dev = dev or usb.core.find(idVendor=VID, idProduct=PID)
        if self.dev is None:
            raise RuntimeError(f"device {{VID:04x}}:{{PID:04x}} not found")
        self.seq = 0
        self.sent = []
        self.session = []
        for cfg in self.dev:
            for intf in cfg:
                if self.dev.is_kernel_driver_active(intf.bInterfaceNumber):
                    try:
                        self.dev.detach_kernel_driver(intf.bInterfaceNumber)
                    except usb.core.USBError:
                        pass
        if handshake and HANDSHAKE:
            self.open()

    def open(self, check=True, timeout=1000):
        """Replay the handshake the vendor app sends when it opens the device (report.md, Handshake).

        Bytes taken from an earlier reply (session token) are copied from this session's replies.
        With check=True a reply whose fixed bytes or checksum differ from the capture raises RuntimeError.
        """
        self.session = []
        for i, step in enumerate(HANDSHAKE, 1):
            reply = None
            if step["read"]:
                bm, req, wv, wi, n = step["setup"]
                reply = bytes(self.dev.ctrl_transfer(bm, req, wv, wi, n, timeout))
            else:
                data = encode(step, (), 0, (), self.session)
                if step["setup"]:
                    bm, req, wv, wi = step["setup"]
                    self.dev.ctrl_transfer(bm, req, wv, wi, data)
                else:
                    self.dev.write(step["endpoint"], data)
                if step["reply"]:
                    r = step["reply"]
                    reply = bytes(self.dev.read(r["endpoint"], max(64, r["length"]), timeout))
            if check and step["reply"]:
                _check_reply(i, step["reply"], reply)
            self.session.append(reply)
        return self.session

    def _send(self, spec, *values, prev=None):
        if prev is None:
            self.sent = []
        if "then" in spec:  # multi-packet transaction
            first = {{k: v for k, v in spec.items() if k != "then"}}
            return [self._send(step, *values, prev=self.sent) for step in [first, *spec["then"]]]
        self.seq += 1
        data = encode(spec, values, self.seq, self.sent, self.session)
        self.sent.append(data)
        if spec["setup"]:
            bm, req, wv, wi = spec["setup"]
            return self.dev.ctrl_transfer(bm, req, wv, wi, data)
        return self.dev.write(spec["endpoint"], data)

    def _query(self, spec, reply, *values, timeout=1000):
        """Send a query (or command), read the device's reply and decode it with parse()."""
        self.sent = []
        if spec is not None:
            self._send(spec, *values)
        if reply["setup"]:
            bm, req, wv, wi, n = reply["setup"]
            data = self.dev.ctrl_transfer(bm, req, wv, wi, n, timeout)
        else:
            data = self.dev.read(reply["endpoint"], max(64, reply["length"]), timeout)
        sent = self.sent[reply["after"]] if len(self.sent) > reply["after"] else b""
        return parse(reply, data, sent)
'''

PARSER = '''
# ---- reply decoder ----
def _get(b, off, width, endian):
    return int.from_bytes(b[off:off + width], "little" if endian == "le" else "big")


def parse(spec, data, sent=b""):
    """Decode a device reply. 'ok' is False when a constant, echoed or checksum byte does not match."""
    data = bytes(data)
    out = {"raw": data.hex(" "), "ok": True}
    if len(data) < spec["length"]:
        out.update(ok=False, error=f"expected {spec['length']} bytes, got {len(data)}")
        return out
    for f in spec["fields"]:
        kind, off, w, end = f["kind"], f["offset"], f["width"], f["endian"]
        raw = _get(data, off, w, end)
        if f.get("signed") and raw >= 1 << (8 * w - 1):  # two's complement (i8/i16)
            raw -= 1 << (8 * w)
        if kind == "const":
            out["ok"] &= raw == f["const"]
        elif kind == "echo":
            if "const" in f:
                out["ok"] &= raw == f["const"]
            elif len(sent) > f["echo"]:
                out["ok"] &= raw == sent[f["echo"]]
        elif kind == "value":
            out[f["name"]] = (raw - f["bias"]) / f["scale"]
        elif kind == "bitfield":
            bits = (int.from_bytes(data[off:off + w], "little") >> f["bit_offset"]) & ((1 << f["bit_width"]) - 1)
            out[f["name"]] = (bits - f["bias"]) / f["scale"]
        elif kind == "reading" and "table" in f:  # mode: the label the vendor app showed for this value
            v = (data[off] >> f["bit_offset"]) & ((1 << f["bit_width"]) - 1) if "bit_width" in f else raw
            out[f["name"]] = f["table"].get(v, v)
        elif kind == "reading" and f.get("bit_width") == 1:  # on/off status flag
            out[f["name"]] = bool((data[off] >> f["bit_offset"]) & 1)
        elif kind == "reading" and "scale" in f:  # named after what the vendor app showed
            if "bit_width" in f:  # a small level packed into part of the byte
                raw = (data[off] >> f["bit_offset"]) & ((1 << f["bit_width"]) - 1)
            v = (raw - f["bias"]) / f["scale"]
            out[f["name"]] = int(v) if v == int(v) else v
        elif kind in ("counter", "reading"):
            out[f["name"]] = raw
        elif kind == "checksum":
            a, z = f["covers"]
            good = raw == compute(f["algo"], data[a:z])
            out["checksum_ok"] = out.get("checksum_ok", True) and good
            out["ok"] &= good
    return out

'''

QUERY = '''
    def {name}({sig}):
        """{doc}
        """
        return self._query({call})
'''


def _ident(name: str) -> str:
    s = re.sub(r"\W+", "_", name).strip("_").lower() or "cmd"
    return s if not s[0].isdigit() else "cmd_" + s


def generate(proto: Protocol) -> str:
    vid = f"0x{proto.vid:04x}" if proto.vid is not None else "None  # TODO: set from lsusb"
    pid = f"0x{proto.pid:04x}" if proto.pid is not None else "None  # TODO: set from lsusb"
    ids = f"{proto.vid:04x}:{proto.pid:04x}" if proto.vid is not None else "(unknown id)"
    out = [HEADER.format(vid=vid, pid=pid, ids=ids, checksums=inspect.getsource(checksums).split('"""', 2)[2])]
    specs = []
    def spec_of(c):
        setup = None
        if c.setup:
            s = c.setup
            setup = (s[0], s[1], s[2] | s[3] << 8, s[4] | s[5] << 8)
        fields = [dict(kind=f.kind, offset=f.offset, width=f.width, endian=f.endian, index=f.index,
                       scale=f.scale, bias=f.bias, table=f.table, step=f.step, algo=f.algo, covers=f.covers,
                       bit_offset=f.bit_offset, bit_width=f.bit_width, source=f.source)
                  for f in c.fields if f.kind in ("value", "bitfield", "lookup", "counter", "checksum")]
        return dict(template=c.template().hex(), endpoint=c.endpoint, setup=setup, fields=fields)

    def command_spec(c):
        spec = spec_of(c)
        spec["fields"] += links.get((c.name, 0), [])
        if c.steps:
            spec["then"] = [spec_of(x) for x in c.steps]
            for k, x in enumerate(spec["then"], 1):
                x["fields"] += links.get((c.name, k), [])
        return spec

    def reply_of(r, prefix):
        setup = None
        if r.source == "control read" and r.query_setup:
            q = r.query_setup
            setup = (q[0], q[1], q[2] | q[3] << 8, q[4] | q[5] << 8, q[6] | q[7] << 8)
        fields = []
        for f in r.fields:
            if f.kind in ("value", "bitfield"):
                name = prefix + (f"_{f.index}" if f.index else "")
            elif f.name:
                name = _ident(f.name) + ("_value" if _ident(f.name) in ("raw", "ok", "error", "checksum_ok") else "")
            else:
                name = f"{f.kind}_{f.offset}"
            d = dict(kind=f.kind, name=name, offset=f.offset, width=f.width, endian=f.endian,
                     const=f.const, echo=f.echo, scale=f.scale, bias=f.bias, algo=f.algo,
                     covers=f.covers, bit_offset=f.bit_offset, bit_width=f.bit_width,
                     signed=f.signed or None, table=f.table if f.kind == "reading" else None)
            fields.append({k: v for k, v in d.items() if v is not None})
        return dict(length=r.length, endpoint=r.endpoint, setup=setup, after=r.packet, fields=fields)

    # handshake: replayed by Device.open(); session tokens are copied from this session's replies
    links: dict[tuple[str, int], list[dict]] = {}
    hs = []
    for st in proto.handshake:
        for t in st["tokens"]:
            for u in t["used_by"]:
                if "command" in u:
                    links.setdefault((u["command"], u["packet"]), []).append(
                        dict(kind="session", offset=u["offset"], width=t["width"], endian="le",
                             step=st["step"] - 1, at=t["reply_offset"]))
        setup = None
        if st["setup"]:
            q = bytes.fromhex(st["setup"])
            setup = (q[0], q[1], q[2] | q[3] << 8, q[4] | q[5] << 8) + ((q[6] | q[7] << 8,) if st["read"] else ())
        fields = [dict(kind="session", offset=u["offset"], width=u["width"], endian="le",
                       step=u["step"] - 1, at=u["reply_offset"]) for u in st["uses"]]
        ck = st["request_checksum"]
        if ck:
            n = len(bytes.fromhex(st["request"]))
            fields.append(dict(kind="checksum", offset=n - ck["width"], width=ck["width"], endian=ck["endian"],
                               algo=ck["algo"], covers=tuple(ck["covers"])))
        reply = None
        if st["reply"]:
            reply = dict(endpoint=st["reply_endpoint"], length=len(bytes.fromhex(st["reply"])), expect=st["expect"])
            if st["reply_checksum"]:
                c = st["reply_checksum"]
                reply["checksum"] = dict(algo=c["algo"], width=c["width"], endian=c["endian"], covers=tuple(c["covers"]))
        hs.append(dict(template=st["request"].replace(" ", ""), endpoint=st["endpoint"], setup=setup,
                       read=st["read"], fields=fields, reply=reply))
    specs.append("# handshake, evidence frames " + ", ".join(str(st["frame"]) for st in proto.handshake) + "\n" if hs else "")
    specs.append(f"HANDSHAKE = {hs!r}\n")

    queries = []
    names = {_ident(c.name) for c in proto.commands}
    for r in proto.responses:
        ident = _ident(r.query)
        const = ident.upper() + "_REPLY"
        specs.append(f"{const} = {reply_of(r, ident)!r}\n")
        lines = "; ".join(f"byte {f.offset}: {f.describe()}" for f in r.fields if f.kind != "const")
        frames = ", ".join(str(s[3]) for s in r.samples[:8])
        doc = f"reply {r.length} bytes; evidence frames {frames}).\n\n        {lines}"
        if r.source == "command":
            c = next(c for c in proto.commands if c.name == r.query)
            args = ", ".join(f"v{i}" for i in range(c.arity))
            sig = f"self, {args}" if args else "self"
            call = f"{ident.upper()}, {const}" + (f", {args}" if args else "")
            queries.append(QUERY.format(name=f"query_{ident}", sig=sig, call=call,
                                        doc=f"Send {r.query} and decode the device's reply ({doc}"))
            continue
        qname = f"query_{ident}" if ident not in names else f"query_{ident}_reply"
        if r.request is not None:
            q = r.request
            if any(f.kind == "unknown" for f in q.fields):
                sent = "the first captured copy verbatim (its varying bytes could not be explained)"
                qspec = dict(template=q.samples[0][1].replace(" ", ""), endpoint=q.endpoint,
                             setup=spec_of(q)["setup"], fields=[])
            else:
                sent = f"`{r.query_payload}`"
                qspec = spec_of(q)
            specs.append(f"{ident.upper()} = {qspec!r}\n")
            how, qarg = f"Send background poll {sent}", ident.upper()
        else:
            how, qarg = f"Read {r.query} (control IN, setup {r.query_setup.hex(' ')})", "None"
        queries.append(QUERY.format(name=qname, sig="self", call=f"{qarg}, {const}",
                                    doc=f"{how} and decode the reply ({doc}"))

    for c in proto.commands:
        const = _ident(c.name).upper()
        spec = command_spec(c)
        specs.append(f"{const} = {spec!r}\n")
        args = ", ".join(f"v{i}" for i in range(c.arity))
        sig = f"self, {args}" if args else "self"
        frames = ", ".join(map(str, c.frames[:8]))
        lines = "; ".join(f"byte {f.offset}: {f.describe()}" for f in c.fields if f.kind not in ("const",))
        out.append(f'''
    def set_{_ident(c.name)}({sig}):
        """{c.name} ({c.confidence:.0%} confidence; evidence frames {frames}).

        {lines}
        """
        return self._send({const}{", " + args if args else ""})
''')
    out += queries
    head, cls = out[0].split("class Device:", 1)
    parser = PARSER if proto.responses else ""
    out[0] = head + parser + "# ---- message specs (from inference) ----\n" + "".join(specs) + "\n\nclass Device:" + cls
    out.append('''

if __name__ == "__main__":
    import sys
    d = Device()
    name, *args = sys.argv[1:]
    fn = getattr(d, name) if name.startswith("query_") else getattr(d, "set_" + name)
    print(fn(*map(float, args)))
''')
    return "".join(out)
