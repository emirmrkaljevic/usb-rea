"""Generate a Wireshark Lua dissector from an inferred protocol.

The dissector is a postdissector: it looks at the payload Wireshark already extracted for every
USB transfer (bulk/interrupt `usb.capdata`, control `usb.data_fragment`, HID `usbhid.data`), matches
it against the inferred commands (endpoint or setup packet, length, constant bytes) and labels each
field, decodes values, and verifies checksums. It is pure Lua with no bit library, so it runs on
Wireshark 3.x (Lua 5.2) and 4.x (Lua 5.4).
"""
from __future__ import annotations
import re

from .infer import Protocol

# name -> (width, lua expression over `d`, a list of byte values)
_LUA_CHECKSUMS = {
    "sum8": "sum(d) % 256",
    "xor8": "xorall(d)",
    "neg_sum8": "(256 - sum(d) % 256) % 256",
    "inv_sum8": "255 - sum(d) % 256",
    "sum16": "sum(d) % 65536",
    "crc8": "crc(d, 8, 0x07, 0x00, false, false, 0x00)",
    "crc8_maxim": "crc(d, 8, 0x31, 0x00, true, true, 0x00)",
    "crc16_ccitt_false": "crc(d, 16, 0x1021, 0xFFFF, false, false, 0x0000)",
    "crc16_xmodem": "crc(d, 16, 0x1021, 0x0000, false, false, 0x0000)",
    "crc16_modbus": "crc(d, 16, 0x8005, 0xFFFF, true, true, 0x0000)",
    "crc16_kermit": "crc(d, 16, 0x1021, 0x0000, true, true, 0x0000)",
}

_HELPERS = r'''
-- ---- arithmetic-only helpers (no bit library needed) ----
local function bxor(a, b)
    local r, p = 0, 1
    while a > 0 or b > 0 do
        if a % 2 ~= b % 2 then r = r + p end
        a, b, p = math.floor(a / 2), math.floor(b / 2), p * 2
    end
    return r
end

local function reflect(v, w)
    local r = 0
    for _ = 1, w do r = r * 2 + v % 2; v = math.floor(v / 2) end
    return r
end

local function sum(d) local s = 0 for _, b in ipairs(d) do s = s + b end return s end
local function xorall(d) local x = 0 for _, b in ipairs(d) do x = bxor(x, b) end return x end

local function crc(d, w, poly, init, refin, refout, xorout)
    local top, mod, c = 2 ^ (w - 1), 2 ^ w, init
    for _, b in ipairs(d) do
        if refin then b = reflect(b, 8) end
        c = bxor(c, b * 2 ^ (w - 8))
        for _ = 1, 8 do
            if c >= top then c = bxor((c * 2) % mod, poly) else c = (c * 2) % mod end
        end
    end
    if refout then c = reflect(c, w) end
    return math.floor(bxor(c, xorout))
end

local function bytes_of(r)
    local t = {}
    for i = 0, r:len() - 1 do t[#t + 1] = r(i, 1):uint() end
    return t
end

-- show the integer the user most likely picked when the raw byte is consistent with it
-- (brightness 25% -> 0x40 -> 25.098 is shown as 25)
local function fmt(v, scale)
    local n = math.floor(v + 0.5)
    if math.abs(v - n) <= 0.5 / math.abs(scale or 1) + 1e-9 then return string.format("%d", n) end
    return string.format("%.4g", v)
end
'''


def _ident(name: str) -> str:
    s = re.sub(r"\W+", "_", name).strip("_").lower() or "cmd"
    return s if not s[0].isdigit() else "cmd_" + s


def _lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def generate(proto: Protocol, name: str = "usbrea") -> str:
    p = _ident(name)
    ids = f"{proto.vid:04x}:{proto.pid:04x}" if proto.vid is not None else "unknown id"
    out = [f'''-- Wireshark dissector for USB device {ids}.
-- Generated by usb-rea (https://github.com/emirmrkaljevic/usb-rea) from captured traffic;
-- every command below is backed by frames listed in the accompanying report.md.
--
-- Use:   wireshark -X lua_script:{p}.lua capture.pcapng
--        tshark -X lua_script:{p}.lua -r capture.pcapng -Y {p}
-- or copy this file to your personal Lua plugins folder (Help > About Wireshark > Folders).
-- Filter fields: {p}.command, {p}.<command>.<field>, {p}.checksum_ok
''']
    out.append(_HELPERS)
    out.append(f'''
local P = Proto({_lua_str(p)}, {_lua_str(f"usb-rea: USB device {ids}")})
local f_command = ProtoField.string("{p}.command", "Command")
local f_checksum_ok = ProtoField.bool("{p}.checksum_ok", "Checksum OK")
local f_unknown = ProtoField.bytes("{p}.unknown", "Unknown bytes")
local fields = {{ f_command, f_checksum_ok, f_unknown }}
local e_bad_checksum = ProtoExpert.new("{p}.checksum_bad", "Checksum mismatch", expert.group.CHECKSUM, expert.severity.WARN)
P.experts = {{ e_bad_checksum }}

local function pf(f) fields[#fields + 1] = f; return f end
''')
    cmds = []
    for c in proto.commands:
        cid = _ident(c.name)
        roles = []
        for f in c.fields:
            if f.kind in ("const", "part"):
                continue
            idx = "" if f.index == 0 else str(f.index)
            if f.kind == "command":
                fid, decl = f"{cid}.command_id", f'ProtoField.uint8("{p}.{cid}.command_id", "Command id", base.HEX)'
            elif f.kind in ("value", "bitfield"):
                label = c.name if f.index == 0 else f"{c.name}[{f.index}]"
                fid = f"{cid}.value{idx}"
                decl = f'ProtoField.double("{p}.{fid}", {_lua_str(label)})'
            elif f.kind == "lookup":
                fid = f"{cid}.value{idx}"
                vs = ", ".join(f"[{v}] = {_lua_str(f'{k:g}')}" for k, v in sorted(f.table.items()))
                decl = f'ProtoField.uint8("{p}.{fid}", {_lua_str(c.name + " (lookup)")}, base.HEX, {{ {vs} }})'
            elif f.kind == "counter":
                fid = f"{cid}.counter"
                decl = f'ProtoField.uint{8 * f.width}("{p}.{fid}", "Sequence counter")'
            elif f.kind == "checksum":
                fid = f"{cid}.checksum"
                decl = f'ProtoField.uint{8 * f.width}("{p}.{fid}", {_lua_str(f.algo)}, base.HEX)'
            else:
                fid, decl = None, None
            var = "f_" + re.sub(r"\W", "_", fid) if fid else "f_unknown"
            if decl:
                out.append(f"local {var} = pf({decl})\n")
            role = {"kind": f.kind, "var": var, "off": f.offset, "w": f.width, "le": f.endian == "le"}
            if f.kind in ("value", "bitfield"):
                role.update(scale=f.scale, bias=f.bias, idx=f.index)
            if f.kind == "bitfield":
                role.update(bo=f.bit_offset, bw=f.bit_width)
            if f.kind == "lookup":
                role.update(idx=f.index, table={v: k for k, v in f.table.items()})
            if f.kind == "checksum":
                role.update(algo=f.algo, a=f.covers[0], z=f.covers[1])
            roles.append(role)
        consts = [(f.offset, f.const) for f in c.fields if f.kind in ("const", "command")]
        setup = None
        if c.setup:
            s = c.setup
            setup = (s[0], s[1], s[2] | s[3] << 8)
        cmds.append((c, cid, roles, consts, setup))

    out.append("\nlocal COMMANDS = {\n")
    for c, cid, roles, consts, setup in cmds:
        frames = ", ".join(map(str, c.frames[:8]))
        out.append(f"    -- {c.name}: {c.confidence:.0%} confidence, evidence frames {frames}\n")
        cs = ", ".join(f"{{{o}, 0x{v:02x}}}" for o, v in consts)
        su = f"{{0x{setup[0]:02x}, 0x{setup[1]:02x}, 0x{setup[2]:04x}}}" if setup else "nil"
        rs = []
        for r in roles:
            parts = [f'kind = "{r["kind"]}"', f'f = {r["var"]}', f'off = {r["off"]}', f'w = {r["w"]}',
                     f'le = {"true" if r["le"] else "false"}']
            for k in ("scale", "bias"):
                if k in r:
                    parts.append(f"{k} = {r[k]!r}")
            for k in ("idx", "bo", "bw", "a", "z"):
                if k in r:
                    parts.append(f"{k} = {r[k]}")
            if "table" in r:
                parts.append("table = { " + ", ".join(f"[{b}] = {v!r}" for b, v in sorted(r["table"].items())) + " }")
            if "algo" in r:
                parts.append(f'check = function(d) return {_LUA_CHECKSUMS[r["algo"]]} end')
            rs.append("            { " + ", ".join(parts) + " },\n")
        out.append(f'''    {{ name = {_lua_str(c.name)}, ep = {c.endpoint}, control = {"true" if setup else "false"}, setup = {su},
      length = {c.length}, consts = {{ {cs} }},
      roles = {{
{"".join(rs)}      }} }},
''')
    out.append("}\n")
    out.append(f'''
P.fields = fields

local fd_capdata = Field.new("usb.capdata")
local fd_fragment = Field.new("usb.data_fragment")
local fd_endpoint = Field.new("usb.endpoint_address")
local fd_reqtype = Field.new("usb.bmRequestType")
local fd_request = Field.new("usb.setup.bRequest")
local fd_wvalue = Field.new("usb.setup.wValue")
local ok_hid, fd_hid = pcall(Field.new, "usbhid.data")
if not ok_hid then fd_hid = nil end

local function payload()
    for _, fd in ipairs({{ fd_capdata, fd_fragment, fd_hid }}) do
        local fi = fd and fd()
        if fi and fi.range and fi.len > 0 then return fi.range end
    end
end

local function matches(c, r)
    if r:len() ~= c.length then return false end
    if c.control then
        local rt, rq, wv = fd_reqtype(), fd_request(), fd_wvalue()
        if not (rt and rq and wv) then return false end
        if rt.value ~= c.setup[1] or rq.value ~= c.setup[2] or wv.value ~= c.setup[3] then return false end
    else
        local ep = fd_endpoint()
        if not ep or ep.value ~= c.ep then return false end
    end
    for _, k in ipairs(c.consts) do
        if r(k[1], 1):uint() ~= k[2] then return false end
    end
    return true
end

local function raw(role, r)
    local s = r(role.off, role.w)
    return role.le and s:le_uint() or s:uint(), s
end

function P.dissector(tvb, pinfo, tree)
    local r = payload()
    if not r then return end
    for _, c in ipairs(COMMANDS) do
        if matches(c, r) then
            local t = tree:add(P, r)
            t:add(f_command, r, c.name)
            local vals, ok = {{}}, nil
            for _, role in ipairs(c.roles) do
                local v, s = raw(role, r)
                local add = role.le and t.add_le or t.add
                if role.kind == "value" then
                    local x = (v - role.bias) / role.scale
                    add(t, role.f, s, x); vals[#vals + 1] = fmt(x, role.scale)
                elseif role.kind == "bitfield" then
                    local bits = math.floor(v / 2 ^ role.bo) % 2 ^ role.bw
                    local x = (bits - role.bias) / role.scale
                    add(t, role.f, s, x):append_text(string.format(" (bits %d-%d)", role.bo, role.bo + role.bw - 1))
                    vals[#vals + 1] = fmt(x, role.scale)
                elseif role.kind == "lookup" then
                    add(t, role.f, s); vals[#vals + 1] = role.table[v] and fmt(role.table[v]) or string.format("0x%02x?", v)
                elseif role.kind == "checksum" then
                    local want = role.check(bytes_of(r(role.a, role.z - role.a)))
                    local item = add(t, role.f, s)
                    ok = (ok ~= false) and (v == want)
                    if v == want then item:append_text(" [correct]")
                    else
                        item:append_text(string.format(" [incorrect, should be 0x%x]", want))
                        item:add_proto_expert_info(e_bad_checksum)
                    end
                elseif role.kind == "unknown" then
                    t:add(f_unknown, s)
                else
                    add(t, role.f, s)
                end
            end
            if ok ~= nil then t:add(f_checksum_ok, ok):set_generated() end
            pinfo.cols.protocol:set({_lua_str(p.upper())})
            pinfo.cols.info:set(c.name .. (#vals > 0 and (" " .. table.concat(vals, " ")) or "")
                .. (ok == false and " [bad checksum]" or ""))
            return
        end
    end
end

register_postdissector(P)
''')
    return "".join(out)
